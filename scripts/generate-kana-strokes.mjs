/**
 * Downloads the kana stroke data for the Write mode into `public/kana-data/`.
 *
 * Source: https://github.com/ailectra/kana-json (tag v0.0.1) — hiragana and
 * katakana in Hanzi Writer's `{ strokes, medians }` format, derived from
 * AnimCJK. The data ships with the app (no CDN at runtime); the drill fetches
 * `/kana-data/<char>.json` lazily, one character at a time.
 *
 * Only the single-glyph characters of the app's catalogue are kept — digraphs
 * are two glyphs and stay out of the Write pool. The script fails loudly if
 * any catalogue character is missing upstream, so a partial download can
 * never ship.
 *
 * License: AnimCJK's kana data is LGPL-3.0-or-later; see
 * public/kana-data/README.md for attribution.
 *
 * Usage: node scripts/generate-kana-strokes.mjs
 */
import { mkdir, readFile, rm, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const TAG = "v0.0.1"
const BASE = `https://raw.githubusercontent.com/ailectra/kana-json/${TAG}/data`

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const outDir = join(root, "public", "kana-data")

// Every single-glyph character in the catalogue, scraped from the
// `c("あ", "ア", ...)` cell declarations in data.ts.
const catalogue = await readFile(join(root, "src/lib/kana/data.ts"), "utf8")
const wanted = new Set()
for (const [, hiragana, katakana] of catalogue.matchAll(
  /c\(\s*"([^"]+)",\s*"([^"]+)"/g
)) {
  if ([...hiragana].length === 1) wanted.add(hiragana)
  if ([...katakana].length === 1) wanted.add(katakana)
}
if (wanted.size === 0) throw new Error("No kana found in data.ts")

await rm(outDir, { recursive: true, force: true })
await mkdir(outDir, { recursive: true })

const failed = []
for (const char of wanted) {
  const response = await fetch(`${BASE}/${encodeURIComponent(char)}.json`)
  if (!response.ok) {
    failed.push(`${char} (${response.status})`)
    continue
  }
  const { strokes, medians } = await response.json()
  if (!Array.isArray(strokes) || !Array.isArray(medians)) {
    failed.push(`${char} (bad shape)`)
    continue
  }
  // char.normalize("NFC") guards against any upstream decomposed filename
  // leaking into ours — the app always looks characters up in NFC.
  await writeFile(
    join(outDir, `${char.normalize("NFC")}.json`),
    JSON.stringify({ strokes, medians })
  )
}

if (failed.length > 0) {
  throw new Error(`Missing stroke data for: ${failed.join(", ")}`)
}

await writeFile(
  join(outDir, "README.md"),
  `# Kana stroke data

One JSON per kana in Hanzi Writer's \`{ strokes, medians }\` format, fetched
lazily by the Write mode as \`/kana-data/<char>.json\`. Generated by
\`scripts/generate-kana-strokes.mjs\` — do not edit by hand.

Source: https://github.com/ailectra/kana-json (${TAG}), derived from
AnimCJK (https://github.com/parsimonhi/animCJK). AnimCJK's kana data is
licensed under the GNU Lesser General Public License v3 or later
(https://www.gnu.org/licenses/lgpl-3.0.html) and is redistributed here
unmodified.
`
)
console.log(`Wrote ${wanted.size} characters to ${outDir}`)
